CREATE TABLE IF NOT EXISTS sales (
    row_id INTEGER,
    order_id TEXT,
    order_date DATE,
    ship_date DATE,
    ship_mode TEXT,
    customer_id TEXT,
    customer_name TEXT,
    segment TEXT,
    country TEXT,
    city TEXT,
    state TEXT,
    postal_code INTEGER,
    region TEXT,
    product_id TEXT,
    category TEXT,
    sub_category TEXT,
    product_name TEXT,
    sales REAL,
    year INTEGER,
    month INTEGER,
    month_name TEXT,
    quarter INTEGER,
    year_month TEXT,
    shipping_days INTEGER
);